"""Provider-neutral research interfaces and evidence validation."""

from __future__ import annotations

from dataclasses import dataclass
import json
from urllib.parse import quote
from urllib.error import URLError, HTTPError
from urllib.request import Request, urlopen
from typing import Protocol, TYPE_CHECKING

from .contracts import Claim, ResearchPacket, ScriptSection, Source, Topic, now_utc

if TYPE_CHECKING:
    from .config import ProjectConfig


class ResearchProvider(Protocol):
    """Capability required to replace the local provisional research adapter."""

    def research(self, topic: Topic) -> ResearchPacket:
        """Return a source-linked research packet for a topic."""


@dataclass(frozen=True)
class AILesson:
    """Structured lesson produced by a language model before scripting."""

    topic: Topic
    summary: str
    sections: tuple[ScriptSection, ...]
    claims: tuple[Claim, ...]
    uncertainty: str
    provider_model: str

    def to_research_packet(self) -> ResearchPacket:
        """Adapt model output to the existing evidence-aware pipeline contract."""
        source = Source(
            title=f"AI-generated lesson: {self.topic.title}",
            citation=f"Generated by {self.provider_model}; not an external source.",
            url=f"ai://{self.provider_model}/{self.topic.key.replace(' ', '-')}",
            source_type="ai-generated",
        )
        return ResearchPacket(
            topic=self.topic,
            summary=self.summary,
            sources=(source,),
            claims=tuple(
                Claim(
                    statement=claim.statement,
                    evidence_level=claim.evidence_level,
                    source_indices=(0,),
                    uncertainty=claim.uncertainty or self.uncertainty,
                )
                for claim in self.claims
            ),
            created_at=now_utc(),
        )


class AILessonProvider(Protocol):
    """Capability for generating a complete lesson from project policy."""

    def generate_lesson(self, topic: Topic, config: "ProjectConfig") -> AILesson:
        """Generate structured lesson content without human intervention."""


class OllamaLessonProvider:
    """Local Ollama adapter using its JSON-generation HTTP endpoint."""

    def __init__(
        self,
        model: str,
        endpoint: str = "http://127.0.0.1:11434/api/generate",
        timeout: int = 180,
        opener=urlopen,
    ) -> None:
        if not model.strip():
            raise ValueError("An Ollama model name is required.")
        self.model = model.strip()
        self.endpoint = endpoint
        self.timeout = timeout
        self.opener = opener

    def generate_lesson(self, topic: Topic, config: "ProjectConfig") -> AILesson:
        required = list(config.required_sections)
        prompt = _lesson_prompt(topic, config)
        request = Request(
            self.endpoint,
            data=json.dumps(
                {
                    "model": self.model,
                    "prompt": prompt,
                    "stream": False,
                    "format": "json",
                    "options": {"temperature": 0.4},
                }
            ).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        try:
            with self.opener(request, timeout=self.timeout) as response:
                outer = json.loads(response.read().decode("utf-8"))
            payload = json.loads(str(outer["response"]))
        except (HTTPError, URLError, TimeoutError, KeyError, TypeError, json.JSONDecodeError) as exc:
            raise RuntimeError(
                f"Ollama lesson generation failed for model '{self.model}': {exc}"
            ) from exc
        try:
            sections = tuple(
                ScriptSection(str(item["heading"]), str(item["text"]))
                for item in payload["sections"]
            )
            if tuple(section.heading for section in sections) != tuple(required):
                raise ValueError("Model returned the wrong lesson section headings.")
            claims = tuple(
                Claim(
                    str(item["statement"]),
                    str(item.get("evidence_level", "model-generated")),
                    (),
                    str(item.get("uncertainty", "")),
                )
                for item in payload["claims"]
            )
            lesson = AILesson(
                topic=topic,
                summary=str(payload["summary"]),
                sections=sections,
                claims=claims,
                uncertainty=str(payload.get("uncertainty", "")),
                provider_model=f"ollama/{self.model}",
            )
        except (KeyError, TypeError, ValueError) as exc:
            raise RuntimeError(f"Ollama returned an invalid lesson shape: {exc}") from exc
        from .quality import require_lesson_quality

        try:
            require_lesson_quality(config, lesson)
        except ValueError as exc:
            raise RuntimeError(f"Ollama returned a lesson that failed quality checks: {exc}") from exc
        return lesson


def create_configured_lesson_provider(config: "ProjectConfig") -> AILessonProvider:
    """Create the configured lesson provider for production execution."""

    tool = next(
        (
            tool
            for tool in config.ai_tools
            if str(tool.get("name", "")).strip().lower() == "script model"
        ),
        {},
    )
    provider = str(tool.get("provider") or "ollama").strip().lower()
    if provider != "ollama":
        raise ValueError(f"Unsupported lesson provider: {provider}")
    model = str(tool.get("model") or "qwen3:4b").strip()
    endpoint = str(
        tool.get("endpoint") or "http://127.0.0.1:11434/api/generate"
    ).strip()
    return OllamaLessonProvider(model=model, endpoint=endpoint)


def _lesson_prompt(topic: Topic, config: "ProjectConfig") -> str:
    sections = "\n".join(f"- {heading}" for heading in config.required_sections)
    rules = "\n".join(f"- {rule}" for rule in config.learning_rules)
    return f"""Create a recreational educational lesson about "{topic.title}" ({topic.subject_area}).
Return JSON only with this exact shape:
{{"summary": "...", "uncertainty": "...", "sections": [{{"heading": "...", "text": "..."}}],
"claims": [{{"statement": "...", "evidence_level": "model-generated", "uncertainty": "..."}}]}}
Use exactly these section headings and make each section useful for a short video:
{sections}
Style and content rules:
{rules}
Avoid invented statistics, citations, quotations, or confident claims you cannot support.
Explain uncertainty plainly. Produce 3-8 concise claims."""


class WikipediaResearchProvider:
    """Free source-backed provider using Wikipedia's public REST API.

    It intentionally returns a conservative packet: the source summary is
    evidence, while claims are limited to statements directly present in that
    summary. A stronger model can later rewrite and cross-check this packet.
    """

    def __init__(self, opener=urlopen, timeout: int = 15) -> None:
        self.opener = opener
        self.timeout = timeout

    def research(self, topic: Topic) -> ResearchPacket:
        url = (
            "https://en.wikipedia.org/api/rest_v1/page/summary/"
            + quote(topic.title.replace(" ", "_"))
        )
        request = Request(url, headers={"User-Agent": "Lattice/0.1 research client"})
        try:
            with self.opener(request, timeout=self.timeout) as response:
                payload = json.loads(response.read().decode("utf-8"))
        except (HTTPError, URLError, TimeoutError, json.JSONDecodeError, KeyError) as exc:
            raise RuntimeError(f"Research provider request failed: {exc}") from exc
        summary = str(payload.get("extract", "")).strip()
        page_url = str(payload.get("content_urls", {}).get("desktop", {}).get("page", ""))
        if not summary or not page_url:
            raise ValueError(f"No credible source summary found for '{topic.title}'.")
        source = Source(topic.title, "Wikipedia article summary", page_url, "encyclopedia")
        claim = Claim(
            statement=summary,
            evidence_level="supported",
            source_indices=(0,),
            uncertainty="Verify important or sensitive claims against independent sources.",
        )
        return ResearchPacket(topic, summary, (source,), (claim,), now_utc())


@dataclass(frozen=True)
class ResearchIssue:
    """A claim or source problem that blocks publication."""

    code: str
    message: str
    claim_index: int | None = None


def validate_research(packet: ResearchPacket) -> tuple[ResearchIssue, ...]:
    """Check claim/source integrity and reject provisional evidence."""

    issues: list[ResearchIssue] = []
    for index, claim in enumerate(packet.claims):
        if claim.evidence_level.strip().lower() in {"unverified", "placeholder"}:
            issues.append(
                ResearchIssue(
                    "unverified-claim",
                    "Claim evidence is provisional and must be replaced.",
                    index,
                )
            )
        if not claim.source_indices:
            issues.append(
                ResearchIssue(
                    "missing-source",
                    "Every claim must reference at least one source.",
                    index,
                )
            )
    if any(source.source_type.strip().lower() == "placeholder" for source in packet.sources):
        issues.append(
            ResearchIssue(
                "placeholder-source",
                "Placeholder sources are not publication-ready.",
            )
        )
    return tuple(issues)


def require_verified_research(packet: ResearchPacket) -> None:
    """Raise a clear error when research cannot enter a production stage."""

    issues = validate_research(packet)
    if issues:
        raise ValueError("; ".join(issue.message for issue in issues))
