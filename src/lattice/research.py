class ResearchProvider(Protocol):
    """Capability required to replace the local provisional research adapter."""

    def research(self, topic: Topic) -> ResearchPacket:
        """Return a source-linked research packet for a topic."""
        ...


class _HttpResponse(Protocol):
    def __enter__(self) -> _HttpResponse: ...
    def __exit__(self, exc_type: object, exc_value: object, traceback: object) -> object: ...
    def read(self) -> bytes: ...


@dataclass(frozen=True)
class AILesson:
    """Structured lesson produced by a language model before scripting."""

    topic: Topic
    summary: str
    sections: tuple[ScriptSection, ...]
    claims: tuple[Claim, ...]
    uncertainty: str
    provider_model: str
    reference_sources: tuple[Source, ...] = ()

    def to_research_packet(self) -> ResearchPacket:
        """Adapt model output to the existing evidence-aware pipeline contract."""
        source = Source(
            title=f"AI-generated lesson: {self.topic.title}",
            citation=f"Generated by {self.provider_model}; not an external source.",
            url=f"ai://{self.provider_model}/{self.topic.key.replace(' ', '-')}",
            source_type="ai-generated",
        )
        return ResearchPacket(
            topic=self.topic,
            summary=self.summary,
            sources=(source, *self.reference_sources),
            claims=tuple(
                Claim(
                    statement=claim.statement,
                    evidence_level=claim.evidence_level,
                    source_indices=(0,),
                    uncertainty=claim.uncertainty or self.uncertainty,
                )
                for claim in self.claims
            ),
            created_at=now_utc(),
        )


class AILessonProvider(Protocol):
    """Capability for generating a complete lesson from project policy."""

    def generate_lesson(self, topic: Topic, config: ProjectConfig) -> AILesson:
        """Generate structured lesson content without human intervention."""
        ...


class OllamaLessonProvider:
    """Local Ollama adapter using its JSON-generation HTTP endpoint."""

    def __init__(
        self,
        model: str,
        endpoint: str = "http://127.0.0.1:11434/api/generate",
        timeout: int = 180,
        opener: Callable[..., _HttpResponse] = urlopen,
    ) -> None:
        if not model.strip():
            raise ValueError("An Ollama model name is required.")
        self.model = model.strip()
        self.endpoint = endpoint
        self.timeout = timeout
        self.opener = opener

    def generate_lesson(self, topic: Topic, config: ProjectConfig) -> AILesson:
        return self._generate(topic, config, "")

    def generate_revision(
        self, topic: Topic, config: ProjectConfig, review: Review
    ) -> AILesson:
        """Regenerate the lesson using the saved rejection context."""

        context = json.dumps(
            {
                "feedback": review.feedback,
                "criteria": review.criteria,
                "markers": [
                    {
                        "start_seconds": marker.start_seconds,
                        "end_seconds": marker.end_seconds,
                        "criterion": marker.criterion,
                        "comment": marker.comment,
                    }
                    for marker in review.markers
                ],
            },
            ensure_ascii=False,
        )
        return self._generate(topic, config, context)

    def generate_grounded_lesson(
        self,
        topic: Topic,
        config: ProjectConfig,
        packet: ResearchPacket,
        review: Review | None = None,
    ) -> AILesson:
        """Supply retrieved sources as context without claiming fact verification."""

        context = json.dumps(
            {
                "research_summary": packet.summary,
                "sources": [
                    {"title": item.title, "citation": item.citation, "url": item.url}
                    for item in packet.sources
                ],
                "review": {
                    "feedback": review.feedback,
                    "criteria": review.criteria,
                    "markers": [
                        {
                            "start_seconds": marker.start_seconds,
                            "end_seconds": marker.end_seconds,
                            "criterion": marker.criterion,
                            "comment": marker.comment,
                        }
                        for marker in review.markers
                    ],
                }
                if review is not None
                else None,
            },
            ensure_ascii=False,
        )
        lesson = self._generate(
            topic,
            config,
            "Ground the explanation in this context; "
            "keep claims labelled model-generated until verified:\n" + context,
        )
        return AILesson(
            lesson.topic,
            lesson.summary,
            lesson.sections,
            lesson.claims,
            lesson.uncertainty,
            lesson.provider_model,
            packet.sources,
        )

    def _generate(
        self, topic: Topic, config: ProjectConfig, revision_context: str
    ) -> AILesson:
        required = list(config.required_sections)
        prompt = _lesson_prompt(topic, config)
        if revision_context:
            prompt += (
                "\nThis is a rejected revision. Address all reviewer feedback, criteria, "
                "and timestamped markers in the new narration and visual plan. "
                "Preserve the required JSON shape and quality rules.\n"
                + revision_context
            )
        request = Request(
            self.endpoint,
            data=json.dumps(
                {
                    "model": self.model,
                    "prompt": prompt,
                    "stream": False,
                    "think": False,
                    "format": "json",
                    "options": {"temperature": 0.4},
                }
            ).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        try:
            with self.opener(request, timeout=self.timeout) as response:
                outer = json.loads(response.read().decode("utf-8"))
            payload = json.loads(str(outer["response"]))
        except (
            HTTPError,
            URLError,
            TimeoutError,
            KeyError,
            TypeError,
            json.JSONDecodeError,
        ) as exc:
            raise RuntimeError(
                f"Ollama lesson generation failed for model '{self.model}': {exc}"
            ) from exc
        try:
            section_items = list(payload["sections"])
            returned_headings = tuple(
                _heading_key(str(item["heading"])) for item in section_items
            )
            expected_headings = tuple(_heading_key(heading) for heading in required)
            if returned_headings != expected_headings:
                raise ValueError("Model returned the wrong lesson section headings.")
            sections = tuple(
                ScriptSection(
                    heading,
                    str(item["text"]),
                    str(item.get("visual_description", "")),
                )
                for heading, item in zip(required, section_items, strict=True)
            )
            claims = tuple(
                Claim(
                    str(item["statement"]),
                    str(item.get("evidence_level", "model-generated")),
                    (),
                    str(item.get("uncertainty", "")),
                )
                for item in payload["claims"]
            )
            lesson = AILesson(
                topic=topic,
                summary=str(payload["summary"]),
                sections=sections,
                claims=claims,
                uncertainty=str(payload.get("uncertainty", "")),
                provider_model=f"ollama/{self.model}",
            )
        except (KeyError, TypeError, ValueError) as exc:
            raise RuntimeError(
                f"Ollama returned an invalid lesson shape: {exc}"
            ) from exc
        from .quality import require_lesson_quality

        try:
            require_lesson_quality(config, lesson)
        except ValueError as exc:
            raise RuntimeError(
                f"Ollama returned a lesson that failed quality checks: {exc}"
            ) from exc
        return lesson


def _heading_key(value: str) -> str:
    """Match harmless heading variations while preserving configured output labels."""

    words = re.sub(r"[^a-z0-9]+", " ", value.lower()).split()
    if words and words[0] in {"a", "an", "the"}:
        words = words[1:]
    return " ".join(words)


def create_configured_lesson_provider(config: ProjectConfig) -> AILessonProvider:
    """Create the configured lesson provider for production execution."""

    tool: dict[str, object] = next(
        (
            tool
            for tool in config.ai_tools
            if str(tool.get("name", "")).strip().lower() == "script model"
        ),
        dict[str, object](),
    )
    provider = str(tool.get("provider") or "ollama").strip().lower()
    if provider != "ollama":
        factory = provider_factory("lesson", provider)
        if factory is None:
            raise ValueError(f"Unsupported lesson provider: {provider}")
        return factory(config, tool)
    model = str(tool.get("model") or "qwen3:4b").strip()
    endpoint = str(
        tool.get("endpoint") or "http://127.0.0.1:11434/api/generate"
    ).strip()
    return OllamaLessonProvider(model=model, endpoint=endpoint)


def create_configured_research_provider(
    config: ProjectConfig,
) -> ResearchProvider | None:
    tool: dict[str, object] = next(
        (
            item
            for item in config.ai_tools
            if str(item.get("name", "")).strip().lower() == "research assistant"
        ),
        dict[str, object](),
    )
    name = str(tool.get("provider") or "").strip().lower()
    if not name:
        if tool.get("required"):
            raise ValueError("A required research assistant needs a provider.")
        return None
    if name == "wikipedia":
        return WikipediaResearchProvider()
    factory = provider_factory("research", name)
    if factory is None:
        raise ValueError(f"Unsupported research provider: {name}")
    return factory(config, tool)


def _lesson_prompt(topic: Topic, config: ProjectConfig) -> str:
    sections = "\n".join(f"- {heading}" for heading in config.required_sections)
    rules = "\n".join(f"- {rule}" for rule in config.learning_rules)
    traits = "\n".join(f"- {trait}" for trait in config.traits)
    max_words = config.max_video_length_seconds * 150 // 60
    return f"""Project brief: {config.lesson_prompt}
Channel: {config.channel_name}. Format: {config.format}.
Create a video production plan about "{topic.title}" ({topic.subject_area}).
Return JSON only with this exact shape:
{{"summary": "...", "uncertainty": "...", "sections": [{{"heading": "...", "text": "spoken narration...", "visual_description": "standalone video-generation prompt..."}}],
"claims": [{{"statement": "...", "evidence_level": "model-generated", "uncertainty": "..."}}]}}
Use exactly these section headings. Treat each section as one scene and one logical
step in the complete explanation:
{sections}
For every scene:
- Write concise spoken narration in "text". Each scene must advance the explanation.
- Make the complete narration only as long as needed for a clear explanation. Do not
  pad, repeat, or slow the explanation to hit a target duration.
- Write a specific, standalone 9:16 video-generation prompt in "visual_description".
- Visually explain the narration instead of merely decorating it. Show the relevant
  subject, initial state, causal action or comparison, and resulting state.
- Specify setting, composition, camera behavior, subject motion, explanatory graphic
  motion, and the transition into the next logical step. Keep continuity across scenes.
- Make every visual description at least 25 words and usable by a video or
  illustration provider without relying on another scene for context.
- Keep recurring subjects, visual motifs, environment, lighting, and palette
  consistent across scenes. Follow the configured traits rather than inventing
  a new house style.
- Do not request baked-in captions, logos, voiceover audio, or visible prompt text.
Configured traits:
{traits}
Learning rules:
{rules}
The finished video must be no longer than {config.max_video_length_seconds} seconds. At an assumed narration pace
of 150 words per minute, the complete spoken script must contain no more than
{max_words} words; use substantially fewer whenever the topic can be explained clearly.
Avoid invented statistics, citations, quotations, or confident claims you cannot support.
Explain uncertainty plainly. Produce 3-8 concise claims."""


class WikipediaResearchProvider:
    """Free source-backed provider using Wikipedia's public REST API.

    It intentionally returns a conservative packet: the source summary is
    evidence, while claims are limited to statements directly present in that
    summary. A stronger model can later rewrite and cross-check this packet.
    """

    def __init__(self, opener: Callable[..., _HttpResponse] = urlopen, timeout: int = 15) -> None:
        self.opener = opener
        self.timeout = timeout

    def research(self, topic: Topic) -> ResearchPacket:
        url = "https://en.wikipedia.org/api/rest_v1/page/summary/" + quote(
            topic.title.replace(" ", "_")
        )
        request = Request(url, headers={"User-Agent": "Lattice/0.1 research client"})
        try:
            with self.opener(request, timeout=self.timeout) as response:
                payload = json.loads(response.read().decode("utf-8"))
        except (
            HTTPError,
            URLError,
            TimeoutError,
            json.JSONDecodeError,
            KeyError,
        ) as exc:
            raise RuntimeError(f"Research provider request failed: {exc}") from exc
        summary = str(payload.get("extract", "")).strip()
        page_url = str(
            payload.get("content_urls", {}).get("desktop", {}).get("page", "")
        )
        if not summary or not page_url:
            raise ValueError(f"No credible source summary found for '{topic.title}'.")
        source = Source(
            topic.title, "Wikipedia article summary", page_url, "encyclopedia"
        )
        claim = Claim(
            statement=summary,
            evidence_level="supported",
            source_indices=(0,),
            uncertainty="Verify important or sensitive claims against independent sources.",
        )
        return ResearchPacket(topic, summary, (source,), (claim,), now_utc())


@dataclass(frozen=True)
class ResearchIssue:
    """A claim or source problem that blocks publication."""

    code: str
    message: str
    claim_index: int | None = None


def validate_research(packet: ResearchPacket) -> tuple[ResearchIssue, ...]:
    """Check claim/source integrity and reject provisional evidence."""

    issues: list[ResearchIssue] = []
    for index, claim in enumerate(packet.claims):
        sources = tuple(packet.sources[item] for item in claim.source_indices)
        if any(source.source_type == "ai-generated" for source in sources):
            if claim.evidence_level.strip().lower() != "model-generated":
                issues.append(
                    ResearchIssue(
                        "unsupported-evidence-label",
                        "An AI-generated source cannot verify a claim.",
                        index,
                    )
                )
            if not claim.uncertainty.strip():
                issues.append(
                    ResearchIssue(
                        "missing-uncertainty",
                        "Model-generated claims need an uncertainty or scope statement.",
                        index,
                    )
                )
        if claim.evidence_level.strip().lower() in {"unverified", "placeholder"}:
            issues.append(
                ResearchIssue(
                    "unverified-claim",
                    "Claim evidence is provisional and must be replaced.",
                    index,
                )
            )
        if not claim.source_indices:
            issues.append(
                ResearchIssue(
                    "missing-source",
                    "Every claim must reference at least one source.",
                    index,
                )
            )
    if any(
        any(
            marker in value.lower()
            for marker in ("placeholder", "example.invalid", "research-required")
        )
        for source in packet.sources
        for value in (source.title, source.citation, source.url, source.source_type)
    ):
        issues.append(
            ResearchIssue(
                "placeholder-source",
                "Placeholder sources are not publication-ready.",
            )
        )
    return tuple(issues)


def require_verified_research(packet: ResearchPacket) -> None:
    """Raise a clear error when research cannot enter a production stage."""

    issues = validate_research(packet)
    if issues:
        raise ValueError("; ".join(issue.message for issue in issues))


